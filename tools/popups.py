"""Writes the popups' rules into accent.css, from GNOME Shell's own stylesheets.

GNOME's popups — menus, Quick Settings, the calendar, dialogs — are near-white in its light
stylesheet, their cards white and their buttons and submenus neutral grey, and in its dark
one neutral greys. Every background (and dimmed text) rule of each stylesheet whose selector
reaches into a popup is copied under the case's style class, .borshevik-glass-light or
.borshevik-glass-dark, in GNOME's order, so GNOME's cascade of states (hover, checked,
default, focus, the accent's) holds among the copies as among its own rules; only its
neutral colours are replaced. Light: the popup the panes' grey with {{light-popup}} % of the
accent, its cards, buttons and submenus the dock's pane, the flat things GNOME paints in the
popup's white clear. Dark: everything 10 % darker than GNOME's, the popup with
{{dark-popup}} % of the accent, its cards, buttons and submenus with {{dark-popup-pane}} %,
white text off-white; in both cases the text takes {{…-text}} % of the accent and the dimmed
text {{…-dim-text}} %. Run it again whenever GNOME Shell's theme changes:

    tools/popups.py [gnome-shell-light.css gnome-shell-dark.css]

With no files it reads the theme of the GNOME Shell installed here. See behaviour#popups in
the extension's spec.
"""
import pathlib
import re
import subprocess
import sys

ACCENT_CSS = pathlib.Path(__file__).resolve().parent.parent / 'borshevik-glass@komorebinator' / 'accent.css'
BEGIN = '/* ---- Popups: generated by tools/popups.py'
END = '/* ---- End of the popups ---- */'

POPUP = 'st-mix(-st-accent-color, rgb(245, 245, 246), {{light-popup}}%)'
PANE = 'st-transparentize(st-mix(-st-accent-color, rgb(235, 235, 236), {{light-surface}}%), 0.444)'
# the cards: the pane as it shows over the popup, but opaque — GNOME stacks notifications one
# on another, and shows a banner over windows
CARD = 'st-mix(st-mix(-st-accent-color, rgb(235, 235, 236), {{light-surface}}%), ' + POPUP + ', 55.6%)'

# what lies in a popup, and what of GNOME's matches those words but is not in one
DOMAIN = re.compile(r'popup-menu-content|candidate-popup-content|\.modal-dialog\b|quick-toggle|quick-settings|'
                    r'\.message\b|message-|events-button|world-clocks-button|weather-button|\.calendar\b|'
                    r'calendar-|\.button\b|icon-button|popup-sub-menu|popup-menu-item|pager-button|datemenu')
EXCLUDE = re.compile(r'login|unlock|screenshot|lg-|Looking|osd|switcher|app-folder|dash|overview|search|'
                     r'workspace|system-action|page-|keyboard|ibus|audio|password|parental|background-app|'
                     r'#panel|panel-button|notification-banner|prompt-dialog|run-dialog|'
                     r'end-session')
CONTAINER = re.compile(r'popup-menu-content|candidate-popup-content|modal-dialog')


LIGHT_DIM = ('#6b6b6e', '#78787b', '#858588')


def recolour_light(colour, selector, prop='background-color'):
    if prop == 'color':
        # GNOME's text takes a little of the accent, its dimmed text — grey, or the text's
        # colour made translucent — more
        dim = 'st-mix(-st-accent-color, @ink@, {{light-dim-text}}%)'
        for grey in LIGHT_DIM:
            colour = colour.replace(grey, dim.replace('@ink@', grey))
        colour = re.sub(r'rgba\(34, 34, 38, ([\d.]+)\)',
                        lambda m: f'st-transparentize({dim}, {1 - float(m[1]):.2f})', colour)
        colour = colour.replace('st-transparentize(#222226,', f'st-transparentize({dim},')
        colour = colour.replace('#222226', 'st-mix(-st-accent-color, #222226, {{light-text}}%)')
        return colour.replace('@ink@', '#222226')
    for grey in ('st-mix(#222226, #fafafb, 12%)', 'st-mix(#222226, #ececf0, 12%)', '#cacad4'):
        colour = colour.replace(grey, PANE)
    colour = colour.replace('#ffffff', CARD)
    colour = colour.replace('whitesmoke', f'st-darken({CARD}, 4%)').replace('#ededed', f'st-darken({CARD}, 7%)')
    if re.search(r'message-close-button|message-expand-button|message-collapse-button|notification-button', selector):
        # a notification's own buttons: GNOME's shade of the text over the card, which
        # left them grey, as the card darkened instead
        colour = re.sub(r'rgba\(34, 34, 38, ([\d.]+)\)',
                        lambda m: f'st-darken({CARD}, {round(float(m[1]) * 40)}%)', colour)
    if 'modal-dialog-button' in selector:
        # a dialog's buttons: GNOME's shade of the text over the dialog, as the panes
        colour = re.sub(r'rgba\(34, 34, 38, ([\d.]+)\)',
                        lambda m: f'st-darken({CARD}, {round((float(m[1]) - 0.1) * 100)}%)', colour)
    # the flat things' states: GNOME's white darkened, as a shade over whatever is under them
    colour = re.sub(r'st-darken\(st-darken\(#fafafb, (\d+)%\), (\d+)%\)',
                    lambda m: f'rgba(34, 34, 38, {(int(m[1]) + int(m[2])) / 100})', colour)
    colour = re.sub(r'st-darken\(#fafafb, (\d+)%\)', lambda m: f'rgba(34, 34, 38, {int(m[1]) / 100})', colour)
    colour = colour.replace('st-lighten(#fafafb, 3%)', 'transparent')
    return colour.replace('#fafafb', POPUP if CONTAINER.search(selector) else 'transparent')


# how much darker than GNOME's the dark popups are, and their text instead of white
DARK_SHADE = 10
DARK_WHITE = '#e6e6e8'
DARK_POPUP = f'st-mix(-st-accent-color, st-darken(#36363a, {DARK_SHADE}%), {{{{dark-popup}}}}%)'
DARK_GREYS = ('st-mix(#ffffff, #36363a, 9%)', 'st-mix(#ffffff, #4a4a4f, 9%)',
              '#47474c', '#54545a', '#56565c', '#45454a', '#3d3d42', '#424247')


def recolour_dark(colour, selector, prop='background-color'):
    if prop == 'color':
        # GNOME's dimmed text — grey, or white at half — takes a little of the accent
        colour = colour.replace('#b2b2b4', 'st-mix(-st-accent-color, #b2b2b4, {{dark-dim-text}}%)')
        # GNOME's white text, off white over the darker popup
        if colour == '#ffffff':
            return f'st-mix(-st-accent-color, {DARK_WHITE}, {{{{dark-text}}}}%)'
        return colour.replace('st-transparentize(#ffffff, 0.5)',
                              'st-transparentize(st-mix(-st-accent-color, #ffffff, {{dark-dim-text}}%), 0.5)')
    # GNOME's greys lighter than the popup keep their lightness and take the dark surfaces'
    # share of the accent, the hue of the dock; marked first, so the popup's own grey inside
    # them is not taken for the popup
    for i, grey in enumerate(DARK_GREYS):
        colour = colour.replace(grey, f'@{i}@')
    colour = re.sub(r'st-lighten\(st-lighten\(#36363a, (\d+)%\), (\d+)%\)',
                    lambda m: f'rgba(255, 255, 255, {(int(m[1]) + int(m[2])) / 100})', colour)
    colour = re.sub(r'st-lighten\(#36363a, (\d+)%\)', lambda m: f'rgba(255, 255, 255, {int(m[1]) / 100})', colour)
    colour = colour.replace('#36363a', DARK_POPUP if CONTAINER.search(selector) else 'transparent')
    for i, grey in enumerate(DARK_GREYS):
        colour = colour.replace(f'@{i}@', f'st-mix(-st-accent-color, st-darken({grey}, {DARK_SHADE}%), {{{{dark-popup-pane}}}}%)')
    if 'modal-dialog-button' in selector:
        # a dialog's buttons: GNOME's shade of white over the dialog, as the buttons
        button = f'st-mix(-st-accent-color, st-darken(st-mix(#ffffff, #36363a, 9%), {DARK_SHADE}%), {{{{dark-popup-pane}}}}%)'
        colour = re.sub(r'rgba\(255, 255, 255, ([\d.]+)\)',
                        lambda m: f'st-lighten({button}, {round((float(m[1]) - 0.1) * 100)}%)', colour)
    return colour


def rules(css, prefix, recolour):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    for m in re.finditer(r'([^{}]+)\{([^}]*)\}', css):
        selectors = [' '.join(s.split()) for s in m.group(1).split(',')]
        selectors = [s for s in selectors if DOMAIN.search(s) and not EXCLUDE.search(s)]
        for prop in ('background-color', 'color'):
            value = re.search(rf'(?<![\w-]){prop}:\s*([^;]+);', m.group(2))
            if not value:
                continue
            by_colour = {}
            for s in selectors:
                # every one copied, those left as GNOME has them too — its accent's
                # foreground on a toggle switched on — so they keep outweighing the rest
                by_colour.setdefault(recolour(value.group(1).strip(), s, prop), []).append(s)
            for colour, group in by_colour.items():
                yield ',\n'.join(f'{prefix} {s}' for s in group) + f' {{\n  {prop}: {colour};\n}}\n'


CASES = {
    'light': ('.borshevik-glass-light', recolour_light, 'rgba(34, 34, 38, 0.12)'),
    'dark': ('.borshevik-glass-dark', recolour_dark, 'rgba(255, 255, 255, 0.08)'),
}


def generate():
    if len(sys.argv) > 2:
        sheets = {'light': pathlib.Path(sys.argv[1]).read_text(), 'dark': pathlib.Path(sys.argv[2]).read_text()}
        source = f'{sys.argv[1]} and {sys.argv[2]}'
    else:
        sheets = {case: subprocess.run(['gresource', 'extract', '/usr/share/gnome-shell/gnome-shell-theme.gresource',
                                        f'/org/gnome/shell/theme/gnome-shell-{case}.css'],
                                       check=True, capture_output=True, text=True).stdout
                  for case in CASES}
        source = subprocess.run(['gnome-shell', '--version'], check=True, capture_output=True, text=True).stdout.strip()
    block = (f'{BEGIN} from {source}; edit the script, not\n'
             '   these. GNOME\'s cascades of popup colours, recoloured per case; its accent states kept as\n'
             '   GNOME has them. ---- */\n')
    counts = []
    for case, (prefix, recolour, outline) in CASES.items():
        generated = list(rules(sheets[case], prefix, recolour))
        counts.append(f'{len(generated)} {case}')
        block += (f'{prefix} .popup-menu-content,\n'
                  f'{prefix} .candidate-popup-content,\n'
                  f'{prefix} .modal-dialog {{\n'
                  f'  border-color: {outline};\n'
                  '}\n' + ''.join(generated))
    block += END + '\n'
    text = ACCENT_CSS.read_text()
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + text[text.index(END) + len(END) + 1:]
    ACCENT_CSS.write_text(text.rstrip('\n') + '\n\n' + block)
    print(f'{" and ".join(counts)} rules from {source}')


if __name__ == '__main__':
    generate()
